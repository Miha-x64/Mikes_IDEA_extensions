// Configure IntelliJ Platform Gradle Plugin - read more: https://plugins.jetbrains.com/docs/intellij/tools-intellij-platform-gradle-plugin-extension.html
intellijPlatform {
    pluginConfiguration {
        name = providers.gradleProperty("pluginName")
        version = providers.gradleProperty("pluginVersion")

        // Extract the <!-- Plugin description --> section from README.md and provide for the plugin's manifest
        description =
            Stream.concat(
                Files.lines(project.file("README.md").toPath())
                    .dropWhile { s -> !s.startsWith("<!-- start plugin.xml -->") }
                    .skip(1)
                    .takeWhile { s -> !s.startsWith("<!-- end plugin.xml -->") },
            Stream.of("<a href=\"https://github.com/Miha-x64/Mikes_IDEA_extensions\">Source code on GitHub</a>")
            )
            .collect(Collectors.joining("\n")).trim()

        // Get the latest available change notes from the changelog file
        changeNotes =
            Files.lines(project.file("CHANGELOG.md").toPath())
                .dropWhile { s -> !s.startsWith("### ${version.get()}") }
                .skip(1)
                .takeWhile { s -> !s.startsWith("###") }
                .collect(Collectors.joining("\n")).trim()

        ideaVersion {
            sinceBuild = providers.gradleProperty("pluginSinceBuild")
//          untilBuild = providers.gradleProperty("pluginUntilBuild")
        }
    }

    signing {
        certificateChain = providers.environmentVariable("CERTIFICATE_CHAIN")
        privateKey = providers.environmentVariable("PRIVATE_KEY")
        password = providers.environmentVariable("PRIVATE_KEY_PASSWORD")
    }

    publishing {
        token = providers.environmentVariable("PUBLISH_TOKEN")
        // The pluginVersion is based on the SemVer (https://semver.org) and supports pre-release labels, like 2.1.7-alpha.3
        // Specify pre-release label to publish the plugin in a custom Release Channel automatically. Read more:
        // https://plugins.jetbrains.com/docs/intellij/deployment.html#specifying-a-release-channel
        channels = providers.gradleProperty("pluginVersion")
            .map { listOf(it.substringAfter('-', "").substringBefore('.').ifEmpty { "default" }) }
    }

    pluginVerification {
        ides {
            recommended()
        }
    }
}

